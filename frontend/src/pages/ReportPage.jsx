import React, { useEffect, useState } from 'react';
import { useSearchParams } from 'react-router-dom';
import { getCompleteness, getTriage, getReportUrl } from '../api';
import FlowTable from '../components/FlowTable';
import FindingsTable from '../components/FindingsTable';

export default function ReportPage() {
  const [params] = useSearchParams();
  const file = params.get('file');
  const [comp, setComp] = useState(null);
  const [tri, setTri] = useState(null);
  const [loading, setLoading] = useState(false);

  useEffect(() => {
    if (!file) return;
    setLoading(true);
    Promise.all([getCompleteness(file), getTriage(file)])
      .then(([c, t]) => { setComp(c.data); setTri(t.data); })
      .finally(() => setLoading(false));
  }, [file]);

  if (!file) return <p className="muted">Upload a PCAP first from the Upload page.</p>;
  if (loading) return <p><span className="loader" /> Generating report…</p>;
  if (!comp || !tri) return null;

  return (
    <div>
      <div className="flex-between no-print">
        <h1>📄 Forensic Report</h1>
        <div>
          <button className="btn btn-primary" onClick={() => window.print()}>
            🖨️ Print
          </button>
          &nbsp;
          <a
            className="btn btn-primary"
            href={getReportUrl(file)}
            target="_blank"
            rel="noreferrer"
          >
            HTML Report ↗
          </a>
        </div>
      </div>

      <div className="card mt-2">
        <h2>Capture Summary</h2>
        <p><strong>File:</strong> {comp.file}</p>
        <p><strong>Packets:</strong> {comp.packet_count} &nbsp;|&nbsp; <strong>Duration:</strong> {comp.duration_sec}s</p>
        <p className="mt-1">
          <strong>Completeness Score: </strong>
          <span
            className={`badge ${
              comp.overall_score >= 80 ? 'badge-high' :
              comp.overall_score >= 50 ? 'badge-med' : 'badge-low'
            }`}
          >
            {comp.overall_score} / 100
          </span>
        </p>
      </div>

      <div className="card">
        <h2>Gap Analysis</h2>
        <table>
          <thead><tr><th>Gap Type</th><th>Count</th></tr></thead>
          <tbody>
            <tr><td>TCP Sequence Gaps</td><td>{comp.gaps.tcp_seq_gaps}</td></tr>
            <tr><td>IP ID Gaps</td><td>{comp.gaps.ip_id_gaps}</td></tr>
            <tr><td>Timestamp Jumps</td><td>{comp.gaps.timestamp_jumps}</td></tr>
            <tr><td>Missing Handshakes</td><td>{comp.gaps.missing_handshakes}</td></tr>
          </tbody>
        </table>
      </div>

      <div className="card">
        <h2>Per-Flow Breakdown</h2>
        <FlowTable flows={comp.flows} />
      </div>

      <div className="card">
        <h2>Threat Findings</h2>
        <FindingsTable findings={tri.findings} />
      </div>

      <div className="card" style={{ color: '#8b949e', fontSize: '.85rem' }}>
        Generated by <strong>PacketTrust</strong> – Capture-Completeness Framework for Evidence-Supported Threat Triage.
        Lab use only.
      </div>
    </div>
  );
}
